-- =========================================================
-- 학교 고장 위치 시스템 DDL (Oracle 12c 이상, 19c 기준)
-- 기준 문서: Notion > ERD 설계
--
-- MySQL 초안과 달라진 이름 (Oracle 예약어·함수명 충돌 회피)
--   floor   -> building_floor   (FLOOR는 Oracle 함수명)
--   level   -> floor_level      (LEVEL은 예약어)
--   type    -> place_type
--   comment -> report_comment   (COMMENT는 예약어)
--   size    -> file_size        (SIZE는 예약어)
-- =========================================================

-- 재실행할 수 있도록 기존 테이블 삭제 (없으면 무시)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('STATUS_HISTORY','REPORT_COMMENT','REPORT_FILE','REPORT',
                                 'CATEGORY','PLACE','BUILDING_FLOOR','BUILDING')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------
-- 학교 지도
-- ---------------------------------------------------------

-- 건물
CREATE TABLE building (
  id          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  code        VARCHAR2(20 CHAR)  NOT NULL,
  name        VARCHAR2(50 CHAR)  NOT NULL,
  sort_order  NUMBER(5)          DEFAULT 0 NOT NULL,
  CONSTRAINT pk_building      PRIMARY KEY (id),
  CONSTRAINT uk_building_code UNIQUE (code)
);
COMMENT ON TABLE  building            IS '건물';
COMMENT ON COLUMN building.code       IS '영문 코드 (main, annex). 배치도 파일 이름에 사용';
COMMENT ON COLUMN building.name       IS '본관, 별관';
COMMENT ON COLUMN building.sort_order IS '건물 탭 표시 순서';

-- 층
CREATE TABLE building_floor (
  id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  building_id    NUMBER(19)          NOT NULL,
  floor_level    NUMBER(3)           NOT NULL,
  name           VARCHAR2(20 CHAR)   NOT NULL,
  map_image_url  VARCHAR2(255 CHAR)  NOT NULL,
  map_width      NUMBER(6),
  map_height     NUMBER(6),
  CONSTRAINT pk_building_floor        PRIMARY KEY (id),
  CONSTRAINT uk_floor_building_level  UNIQUE (building_id, floor_level),
  CONSTRAINT fk_floor_building        FOREIGN KEY (building_id) REFERENCES building (id)
);
COMMENT ON TABLE  building_floor               IS '층';
COMMENT ON COLUMN building_floor.floor_level   IS '1, 2, 3 (지하는 -1)';
COMMENT ON COLUMN building_floor.name          IS '화면 표시용 (1층, B1)';
COMMENT ON COLUMN building_floor.map_image_url IS '배치도 경로 (/static/maps/main_2F.svg)';
COMMENT ON COLUMN building_floor.map_width     IS '원본 배치도 가로(px)';
COMMENT ON COLUMN building_floor.map_height    IS '원본 배치도 세로(px)';

-- 교실·시설 영역 (배치도 위 사각형, 0~1 비율 좌표)
CREATE TABLE place (
  id          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  floor_id    NUMBER(19)         NOT NULL,
  name        VARCHAR2(50 CHAR)  NOT NULL,
  place_type  VARCHAR2(20)       NOT NULL,
  x           NUMBER(5,4)        NOT NULL,
  y           NUMBER(5,4)        NOT NULL,
  width       NUMBER(5,4)        NOT NULL,
  height      NUMBER(5,4)        NOT NULL,
  CONSTRAINT pk_place       PRIMARY KEY (id),
  CONSTRAINT fk_place_floor FOREIGN KEY (floor_id) REFERENCES building_floor (id),
  CONSTRAINT ck_place_type  CHECK (place_type IN ('CLASSROOM','SPECIAL','TOILET','HALL','STAIRS','OFFICE','ETC')),
  CONSTRAINT ck_place_range CHECK (x BETWEEN 0 AND 1 AND y BETWEEN 0 AND 1
                                   AND width > 0 AND height > 0
                                   AND x + width <= 1 AND y + height <= 1)
);
CREATE INDEX idx_place_floor ON place (floor_id);
COMMENT ON TABLE  place            IS '교실·시설 영역';
COMMENT ON COLUMN place.name       IS '2-3반, 과학실, 남자 화장실';
COMMENT ON COLUMN place.place_type IS 'CLASSROOM, SPECIAL, TOILET, HALL, STAIRS, OFFICE, ETC';

-- ---------------------------------------------------------
-- 신고
-- ---------------------------------------------------------

-- 신고 분류
CREATE TABLE category (
  id          NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  name        VARCHAR2(30 CHAR)  NOT NULL,
  sort_order  NUMBER(5)          DEFAULT 0 NOT NULL,
  CONSTRAINT pk_category      PRIMARY KEY (id),
  CONSTRAINT uk_category_name UNIQUE (name)
);
COMMENT ON TABLE category IS '신고 분류';

-- 신고
CREATE TABLE report (
  id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  floor_id       NUMBER(19)          NOT NULL,
  place_id       NUMBER(19),
  category_id    NUMBER(19)          NOT NULL,
  title          VARCHAR2(100 CHAR)  NOT NULL,
  content        VARCHAR2(4000 CHAR) NOT NULL,
  pos_x          NUMBER(5,4)         NOT NULL,
  pos_y          NUMBER(5,4)         NOT NULL,
  status         VARCHAR2(10)        DEFAULT 'RECEIVED' NOT NULL,
  reporter_name  VARCHAR2(30 CHAR),
  created_at     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_report          PRIMARY KEY (id),
  CONSTRAINT fk_report_floor    FOREIGN KEY (floor_id)    REFERENCES building_floor (id),
  CONSTRAINT fk_report_place    FOREIGN KEY (place_id)    REFERENCES place (id) ON DELETE SET NULL,
  CONSTRAINT fk_report_category FOREIGN KEY (category_id) REFERENCES category (id),
  CONSTRAINT ck_report_status   CHECK (status IN ('RECEIVED','DONE','HOLD')),
  CONSTRAINT ck_report_pos      CHECK (pos_x BETWEEN 0 AND 1 AND pos_y BETWEEN 0 AND 1)
);
CREATE INDEX idx_report_floor          ON report (floor_id);
CREATE INDEX idx_report_place          ON report (place_id);
CREATE INDEX idx_report_category       ON report (category_id);
CREATE INDEX idx_report_status_created ON report (status, created_at);
COMMENT ON TABLE  report               IS '신고';
COMMENT ON COLUMN report.floor_id      IS '핀이 찍힌 층';
COMMENT ON COLUMN report.place_id      IS '핀이 들어간 교실 영역 (복도 등은 NULL)';
COMMENT ON COLUMN report.content       IS '신고 내용 (최대 4000자)';
COMMENT ON COLUMN report.pos_x         IS '핀 x 좌표 (0~1)';
COMMENT ON COLUMN report.pos_y         IS '핀 y 좌표 (0~1)';
COMMENT ON COLUMN report.status        IS 'RECEIVED 접수, DONE 완료, HOLD 보류';
COMMENT ON COLUMN report.reporter_name IS '선택 입력 (로그인 없음)';

-- 첨부 파일 (파일 자체는 서버 폴더/S3, DB에는 정보만)
CREATE TABLE report_file (
  id             NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  report_id      NUMBER(19)          NOT NULL,
  original_name  VARCHAR2(255 CHAR)  NOT NULL,
  stored_path    VARCHAR2(255 CHAR)  NOT NULL,
  content_type   VARCHAR2(50)        NOT NULL,
  file_size      NUMBER(12)          NOT NULL,
  created_at     TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_report_file        PRIMARY KEY (id),
  CONSTRAINT uk_report_file_path   UNIQUE (stored_path),
  CONSTRAINT fk_report_file_report FOREIGN KEY (report_id) REFERENCES report (id) ON DELETE CASCADE,
  CONSTRAINT ck_report_file_size   CHECK (file_size > 0)
);
CREATE INDEX idx_report_file_report ON report_file (report_id);
COMMENT ON TABLE  report_file               IS '첨부 파일';
COMMENT ON COLUMN report_file.original_name IS '사용자가 올린 파일 이름';
COMMENT ON COLUMN report_file.stored_path   IS '서버 저장 경로 (UUID 파일명)';
COMMENT ON COLUMN report_file.content_type  IS 'image/jpeg, image/png';
COMMENT ON COLUMN report_file.file_size     IS '바이트';

-- 관리자 답글
CREATE TABLE report_comment (
  id          NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  report_id   NUMBER(19)          NOT NULL,
  content     VARCHAR2(2000 CHAR) NOT NULL,
  created_at  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_report_comment PRIMARY KEY (id),
  CONSTRAINT fk_comment_report FOREIGN KEY (report_id) REFERENCES report (id) ON DELETE CASCADE
);
CREATE INDEX idx_comment_report ON report_comment (report_id);
COMMENT ON TABLE report_comment IS '관리자 답글';

-- 상태 변경 기록
CREATE TABLE status_history (
  id           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
  report_id    NUMBER(19)          NOT NULL,
  from_status  VARCHAR2(10)        NOT NULL,
  to_status    VARCHAR2(10)        NOT NULL,
  reason       VARCHAR2(255 CHAR),
  changed_at   TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_status_history        PRIMARY KEY (id),
  CONSTRAINT fk_status_history_report FOREIGN KEY (report_id) REFERENCES report (id) ON DELETE CASCADE,
  CONSTRAINT ck_status_history_from   CHECK (from_status IN ('RECEIVED','DONE','HOLD')),
  CONSTRAINT ck_status_history_to     CHECK (to_status   IN ('RECEIVED','DONE','HOLD'))
);
CREATE INDEX idx_status_history_report ON status_history (report_id, changed_at);
COMMENT ON TABLE  status_history        IS '상태 변경 기록';
COMMENT ON COLUMN status_history.reason IS '보류 사유 등';

-- ---------------------------------------------------------
-- updated_at 자동 갱신 (MySQL의 ON UPDATE CURRENT_TIMESTAMP 대신)
-- ---------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_report_updated_at
BEFORE UPDATE ON report
FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/

CREATE OR REPLACE TRIGGER trg_comment_updated_at
BEFORE UPDATE ON report_comment
FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/
